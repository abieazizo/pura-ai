/**
 * The curated commerce catalog — the ONLY pool the recommendation engine picks
 * from. Real, mainstream products with honest approximate prices.
 *
 * Images: `image: require(...)` where a real packshot ships in assets/ (the
 * routine cards bleed these past the card edge); null → the card's quiet
 * brand-tile fallback renders until the packshot is added. Never a vector,
 * never an emoji.
 *
 * Blurbs are PLAIN WORDS (no barrier/sebum/actives/exfoliant jargon — that
 * vocabulary is banned from user-facing copy; internal fields like
 * `activeStrength` never render).
 *
 * Affiliate URLs are Amazon product-intent searches tagged for the affiliate
 * program; the Buy button's backend is swappable (owned checkout later) and
 * reads these as opaque handoff targets.
 */

import type { CommerceSku } from './types';

const amazon = (q: string) =>
  `https://www.amazon.com/s?k=${encodeURIComponent(q)}&tag=puraai-20`;

/**
 * Resolve a packshot's static require. Under Metro the literal require inside
 * the thunk bundles normally (it stays statically analyzable); under Node/tsx
 * (the verifier scripts) requiring a JPEG throws, and we fall back to null —
 * the engine and screens treat that exactly like a SKU without a packshot.
 */
const img = (load: () => number): number | null => {
  try {
    return load();
  } catch {
    return null;
  }
};

