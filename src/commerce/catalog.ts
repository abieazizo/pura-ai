/** Honest catalog audit used by the verifier: every step must offer at least
 *  one budget-tier SKU, or the "always offer a budget alternative" promise
 *  can't be kept. */
export function catalogBudgetCoverage(): Record<string, number> {
  const cover: Record<string, number> = {};
  for (const sku of COMMERCE_CATALOG) {
    if (sku.priceTier === 'budget') cover[sku.step] = (cover[sku.step] ?? 0) + 1;
  }
  return cover;
}
